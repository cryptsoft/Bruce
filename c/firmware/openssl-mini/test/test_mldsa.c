static size_t from_hex(const char *h, uint8_t *o, size_t max)
{
    size_t n = strlen(h) / 2;
    if (n > max) return 0;
    for (size_t i = 0; i < n; i++) {
        unsigned v; sscanf(h + 2 * i, "%2x", &v); o[i] = (uint8_t)v;
    }
    return n;
}

