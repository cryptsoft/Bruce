#define MAXPK  2600
#define MAXSIG 4700
#define MAXMSG 256

static void test_keygen_kat(void)
{
    static const struct { int variant; const char *pk; } v[] = {
        { PQF_MLDSA_44, KEYGEN_PK_44 },
        { PQF_MLDSA_65, KEYGEN_PK_65 },
        { PQF_MLDSA_87, KEYGEN_PK_87 },
    };
    uint8_t seed[32];
    from_hex(KEYGEN_SEED, seed, sizeof seed);

    printf("-- keygen known-answer (RFC 9881 seed) --\n");
    for (size_t i = 0; i < sizeof v / sizeof v[0]; i++) {
        char label[64];
        uint8_t want[MAXPK], got[MAXPK];
        size_t want_len = from_hex(v[i].pk, want, sizeof want);
        size_t got_len = 0;

        snprintf(label, sizeof label,
                 "ML-DSA-%d seed -> public key exact bytes", v[i].variant);
        if (pqf_mldsa_pub_from_seed(v[i].variant, seed, got, &got_len) != 0) {
            fprintf(stderr, "FAIL: %s (derive failed)\n", label);
            fails++;
            continue;
        }
        CHECK(got_len == want_len && memcmp(got, want, want_len) == 0, label);
    }
}

static void test_sign_kat(void)
{
    printf("-- deterministic sign known-answer --\n");
    for (size_t i = 0; i < sizeof SIGN_KATS / sizeof SIGN_KATS[0]; i++) {
        const struct sign_kat *k = &SIGN_KATS[i];
        char label[80];
        uint8_t seed[32], msg[MAXMSG], want[MAXSIG], got[MAXSIG];
        uint8_t pub[MAXPK];
        size_t msg_len, want_len, got_len = 0, pub_len = 0;

        from_hex(k->seed, seed, sizeof seed);
        msg_len = from_hex(k->msg, msg, sizeof msg);
        want_len = from_hex(k->sig, want, sizeof want);

        snprintf(label, sizeof label,
                 "ML-DSA-%d deterministic signature exact bytes", k->variant);
        if (pqf_mldsa_sign(k->variant, seed, msg, msg_len, got, &got_len) != 0) {
            fprintf(stderr, "FAIL: %s (sign failed)\n", label);
            fails++;
            continue;
        }
        CHECK(got_len == want_len && memcmp(got, want, want_len) == 0, label);

        /* The verifier must accept the vector signature, not just one
         * this build produced. */
        if (pqf_mldsa_pub_from_seed(k->variant, seed, pub, &pub_len) != 0) {
            fprintf(stderr, "FAIL: ML-DSA-%d derive for verify\n", k->variant);
            fails++;
            continue;
        }
        snprintf(label, sizeof label,
                 "ML-DSA-%d verify accepts the vector signature", k->variant);
        CHECK(pqf_mldsa_verify(k->variant, pub, pub_len, msg, msg_len,
                               want, want_len) == 1, label);

        /* Single-bit flip in the signature. */
        want[want_len / 2] ^= 0x01;
        snprintf(label, sizeof label,
                 "ML-DSA-%d rejects 1-bit flip in the signature", k->variant);
        CHECK(pqf_mldsa_verify(k->variant, pub, pub_len, msg, msg_len,
                               want, want_len) == 0, label);
        want[want_len / 2] ^= 0x01;

        /* Single-bit flip in the message. */
        if (msg_len > 0) msg[msg_len / 2] ^= 0x01;
        snprintf(label, sizeof label,
                 "ML-DSA-%d rejects 1-bit flip in the message", k->variant);
        CHECK(msg_len > 0
              && pqf_mldsa_verify(k->variant, pub, pub_len, msg, msg_len,
                                  want, want_len) == 0, label);
    }
}

/* Sign the same vectors through the full key-generation path.
 *
 * pqf_mldsa_sign() expands only what ML-DSA.Sign() reads
 * (ossl_ml_dsa_generate_key_for_sign()); pqf_mldsa_pub_from_seed() runs
 * the full ossl_ml_dsa_generate_key(). This drives the full path into
 * ossl_ml_dsa_sign() directly with rnd = 0^32 and holds the result to
 * the published bytes, so the two expansions are shown to yield the
 * same signing material and not merely to agree with each other. */
static void test_full_keygen_sign(void)
{
    static const struct { int variant; int evp_type; } map[] = {
        { PQF_MLDSA_44, EVP_PKEY_ML_DSA_44 },
        { PQF_MLDSA_65, EVP_PKEY_ML_DSA_65 },
        { PQF_MLDSA_87, EVP_PKEY_ML_DSA_87 },
    };
    static const uint8_t rnd[32] = { 0 };

    printf("-- full-keygen signing path --\n");
    for (size_t i = 0; i < sizeof SIGN_KATS / sizeof SIGN_KATS[0]; i++) {
        const struct sign_kat *k = &SIGN_KATS[i];
        char label[96];
        uint8_t seed[32], msg[MAXMSG], want[MAXSIG], got[MAXSIG];
        size_t msg_len, want_len, got_len = 0;
        int evp_type = 0;

        for (size_t j = 0; j < sizeof map / sizeof map[0]; j++)
            if (map[j].variant == k->variant)
                evp_type = map[j].evp_type;

        from_hex(k->seed, seed, sizeof seed);
        msg_len = from_hex(k->msg, msg, sizeof msg);
        want_len = from_hex(k->sig, want, sizeof want);

        ML_DSA_KEY *key = ossl_ml_dsa_key_new(NULL, NULL, evp_type);
        int ok = key != NULL
            && ossl_ml_dsa_set_prekey(key, 1 /*prefer_seed*/, 0 /*retain*/,
                                      seed, sizeof seed, NULL, 0) == 1
            && ossl_ml_dsa_generate_key(key) == 1
            && ossl_ml_dsa_sign(key, 0 /*msg_is_mu*/, msg, msg_len,
                                NULL, 0 /*context*/, rnd, sizeof rnd,
                                1 /*encode*/, got, &got_len,
                                ossl_ml_dsa_key_get_sig_len(key)) == 1;
        ossl_ml_dsa_key_free(key);

        snprintf(label, sizeof label,
                 "ML-DSA-%d full keygen + ossl_ml_dsa_sign match the vector",
                 k->variant);
        CHECK(ok && got_len == want_len && memcmp(got, want, want_len) == 0,
              label);
    }
}

static void test_digest_kats(void)
{
    printf("-- digest vectors (seed/message spread) --\n");
    for (size_t i = 0; i < sizeof DIGEST_KATS / sizeof DIGEST_KATS[0]; i++) {
        const struct dgst_kat *k = &DIGEST_KATS[i];
        char label[96];
        uint8_t seed[32], msg[MAXMSG], want[32], dg[32];
        uint8_t pub[MAXPK], sig[MAXSIG];
        size_t msg_len, pub_len = 0, sig_len = 0;

        from_hex(k->seed, seed, sizeof seed);
        msg_len = from_hex(k->msg, msg, sizeof msg);

        snprintf(label, sizeof label,
                 "ML-DSA-%d seed %.4s.. msg %zuB: public key digest",
                 k->variant, k->seed, msg_len);
        if (pqf_mldsa_pub_from_seed(k->variant, seed, pub, &pub_len) != 0) {
            fprintf(stderr, "FAIL: %s (derive failed)\n", label);
            fails++;
            continue;
        }
        pqf_sha256(pub, pub_len, dg);
        from_hex(k->pk_dg, want, sizeof want);
        CHECK(memcmp(dg, want, 32) == 0, label);

        snprintf(label, sizeof label,
                 "ML-DSA-%d seed %.4s.. msg %zuB: signature digest",
                 k->variant, k->seed, msg_len);
        if (pqf_mldsa_sign(k->variant, seed, msg, msg_len, sig, &sig_len) != 0) {
            fprintf(stderr, "FAIL: %s (sign failed)\n", label);
            fails++;
            continue;
        }
        pqf_sha256(sig, sig_len, dg);
        from_hex(k->sig_dg, want, sizeof want);
        CHECK(memcmp(dg, want, 32) == 0, label);

        /* The signature just matched the vector, so this is a round trip
         * against the reference bytes, not merely against this build. */
        snprintf(label, sizeof label,
                 "ML-DSA-%d seed %.4s.. msg %zuB: wrapper round-trip",
                 k->variant, k->seed, msg_len);
        CHECK(pqf_mldsa_verify(k->variant, pub, pub_len, msg, msg_len,
                               sig, sig_len) == 1, label);
        sig[sig_len - 1] ^= 0x01;
        snprintf(label, sizeof label,
                 "ML-DSA-%d seed %.4s.. msg %zuB: wrapper 1-bit flip rejected",
                 k->variant, k->seed, msg_len);
        CHECK(pqf_mldsa_verify(k->variant, pub, pub_len, msg, msg_len,
                               sig, sig_len) == 0, label);
    }
}

static void test_variant(int variant, size_t exp_pk, size_t exp_sig)
{
    char label[80];
    printf("-- ML-DSA-%d self-consistency --\n", variant);

    uint8_t seed[32];
    for (int i = 0; i < 32; i++) seed[i] = (uint8_t)(i + variant);

    uint8_t pub[MAXPK]; size_t pub_len = 0;
    CHECK(pqf_mldsa_pub_from_seed(variant, seed, pub, &pub_len) == 0,
          "derive public key from seed");
    snprintf(label, sizeof label, "public key length = %zu", exp_pk);
    CHECK(pub_len == exp_pk, label);

    /* Determinism: same seed -> same public key. */
    uint8_t pub2[MAXPK]; size_t pub2_len = 0;
    pqf_mldsa_pub_from_seed(variant, seed, pub2, &pub2_len);
    CHECK(pub2_len == pub_len && memcmp(pub, pub2, pub_len) == 0,
          "keygen is deterministic from the seed");

    const char *msg = "Bruce hybrid signing test message";
    uint8_t sig[MAXSIG]; size_t sig_len = 0;
    CHECK(pqf_mldsa_sign(variant, seed, (const uint8_t *)msg, strlen(msg),
                         sig, &sig_len) == 0, "sign");
    snprintf(label, sizeof label, "signature length = %zu", exp_sig);
    CHECK(sig_len == exp_sig, label);

    /* Determinism: same (seed, message) -> same signature. */
    uint8_t sig2[MAXSIG]; size_t sig2_len = 0;
    pqf_mldsa_sign(variant, seed, (const uint8_t *)msg, strlen(msg),
                   sig2, &sig2_len);
    CHECK(sig2_len == sig_len && memcmp(sig, sig2, sig_len) == 0,
          "signing is deterministic from the seed");

    CHECK(pqf_mldsa_verify(variant, pub, pub_len,
                           (const uint8_t *)msg, strlen(msg),
                           sig, sig_len) == 1, "verify accepts good signature");

    /* Tamper the message -> verify must reject. */
    char bad[64]; strcpy(bad, msg); bad[0] ^= 0x01;
    CHECK(pqf_mldsa_verify(variant, pub, pub_len,
                           (const uint8_t *)bad, strlen(bad),
                           sig, sig_len) == 0, "verify rejects altered message");

    /* Tamper the signature -> reject. */
    sig[10] ^= 0x80;
    CHECK(pqf_mldsa_verify(variant, pub, pub_len,
                           (const uint8_t *)msg, strlen(msg),
                           sig, sig_len) == 0, "verify rejects altered signature");

    /* Tamper the public key -> reject. */
    sig[10] ^= 0x80;
    pub[pub_len - 1] ^= 0x01;
    CHECK(pqf_mldsa_verify(variant, pub, pub_len,
                           (const uint8_t *)msg, strlen(msg),
                           sig, sig_len) == 0, "verify rejects altered public key");
}

int main(void)
{
    printf("pqf ML-DSA host tests\n");
    test_keygen_kat();
    test_sign_kat();
    test_full_keygen_sign();
    test_digest_kats();
    test_variant(PQF_MLDSA_44, PQF_MLDSA44_PK_LEN, PQF_MLDSA44_SIG_LEN);
    test_variant(PQF_MLDSA_65, PQF_MLDSA65_PK_LEN, PQF_MLDSA65_SIG_LEN);
    test_variant(PQF_MLDSA_87, PQF_MLDSA87_PK_LEN, PQF_MLDSA87_SIG_LEN);
    printf("\n%d failure(s)\n", fails);
    return fails ? 1 : 0;
}
